def panel(d, cx, cy, w, h, col, text=None, t=0.0, fs=40, alpha=1.0, pop=1.0):
    """Floating holographic countdown panel."""
    w, h = w * pop, h * pop
    if w < 4:
        return
    cy += math.sin(t * 3 + cx * 0.01) * h * 0.06

    def a(v):
        return int(clamp(v * alpha, 0, 255))

    for i in range(7, 0, -1):
        g = i * h * 0.07
        d.rounded_rectangle([cx - w / 2 - g, cy - h / 2 - g, cx + w / 2 + g, cy + h / 2 + g],
                            radius=h * 0.3 + g, outline=col + (a(12 + (8 - i) * 3),),
                            width=max(2, int(h * 0.06)))
    d.rounded_rectangle([cx - w / 2, cy - h / 2, cx + w / 2, cy + h / 2], radius=h * 0.25,
                        fill=shade(col, 0.1) + (a(190),), outline=col + (a(255),),
                        width=max(2, int(h * 0.05)))
    yy = cy - h / 2 + 5
    while yy < cy + h / 2 - 4:
        d.line([(cx - w / 2 + 6, yy), (cx + w / 2 - 6, yy)], fill=col + (a(26),))
        yy += max(4, h * 0.13)
    if text:
        light = tuple(min(255, c + 170) for c in col)
        d.text((cx, cy), text, font=mono(fs), fill=light + (a(255),), anchor="mm",
               stroke_width=max(1, fs // 26), stroke_fill=col + (a(255),))
    else:
        for k in range(3):
            d.line([(cx - w * 0.3, cy - h * 0.2 + k * h * 0.2), (cx + w * (0.3 - 0.08 * k), cy - h * 0.2 + k * h * 0.2)],
                   fill=col + (a(120),), width=max(2, int(h * 0.05)))


