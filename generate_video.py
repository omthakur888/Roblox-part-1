def _load(paths, size):
    for p in paths:
        try:
            return ImageFont.truetype(p, size)
        except OSError:
            continue
    try:
        return ImageFont.load_default(size)
    except TypeError:
        return ImageFont.load_default()


@lru_cache(maxsize=None)
def font(size):
    return _load(SANS, int(size))


@lru_cache(maxsize=None)
def mono(size):
    return _load(MONO, int(size))


def wrap(text, fnt, maxw):
    words, lines, cur = text.split(), [], ""
    for w in words:
        test = (cur + " " + w).strip()
        if fnt.getlength(test) <= maxw:
            cur = test
        else:
            if cur:
                lines.append(cur)
            cur = w
    if cur:
        lines.append(cur)
    return lines


@lru_cache(maxsize=64)
def _gradient(top, bottom):
    t = np.linspace(0, 1, H, dtype=np.float32)[:, None, None]
    a = np.array(top, np.float32)[None, None, :]
    b = np.array(bottom, np.float32)[None, None, :]
    arr = np.repeat(a * (1 - t) + b * t, W, axis=1).astype(np.uint8)
    return Image.fromarray(arr)


def canvas(top, bottom):
    return _gradient(tuple(top), tuple(bottom)).copy()


