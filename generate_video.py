def noise_sig(n, seed=0):
    return np.random.default_rng(seed).uniform(-1, 1, n)


def lowpass(x, k):
    return np.convolve(x, np.ones(k) / k, mode="same")


def add(buf, start, sig, gain=1.0):
    i = int(start * SR)
    if i < 0 or i >= len(buf):
        return
    j = min(len(buf), i + len(sig))
    buf[i:j] += sig[: j - i] * gain


def thump(f0=48, f1=120, dur=0.45, decay=9.0):
    n = int(SR * dur)
    t = np.arange(n) / SR
    freq = f0 + (f1 - f0) * np.exp(-t * 30)
    return np.sin(2 * np.pi * np.cumsum(freq) / SR) * np.exp(-t * decay)


def heartbeat():
    s = np.zeros(int(SR * 0.7))
    add(s, 0.0, thump(), 1.0)
    add(s, 0.2, thump(45, 95, 0.4, 11), 0.7)
    return s


def click():
    n = int(SR * 0.03)
    t = np.arange(n) / SR
    return noise_sig(n, 1) * np.exp(-t * 220) * 0.6 + np.sin(2 * np.pi * 2400 * t) * np.exp(-t * 300) * 0.5


def ding(f=1318.0):
    n = int(SR * 0.9)
    t = np.arange(n) / SR
    x = np.sin(2 * np.pi * f * t) + 0.4 * np.sin(2 * np.pi * 2 * f * t) + 0.2 * np.sin(2 * np.pi * 3.01 * f * t)
    return x * np.exp(-t * 5) * 0.5


def footstep(seed):
    n = int(SR * 0.12)
    t = np.arange(n) / SR
    return lowpass(noise_sig(n, seed), 40) * np.exp(-t * 35) * 3.0


def whoosh(dur=0.5, seed=3):
    n = int(SR * dur)
    t = np.arange(n) / SR
    x = lowpass(noise_sig(n, seed), 12)
    return x * np.sin(np.pi * t / dur) ** 2 * 2.0


def breath(seed):
    n = int(SR * 0.5)
    t = np.arange(n) / SR
    return lowpass(noise_sig(n, seed), 6) * np.sin(np.pi * t / 0.5) ** 2 * 1.6


def glitch_burst(seed, dur=0.12):
    n = int(SR * dur)
    r = np.random.default_rng(seed)
    x = r.uniform(-1, 1, n)
    gate = np.repeat(r.integers(0, 2, n // 400 + 1), 400)[:n]
    x = np.round(x * 4) / 4 * gate
    return x * np.exp(-np.arange(n) / SR * 12)


def beep(f=1800.0, dur=0.12):
    n = int(SR * dur)
    t = np.arange(n) / SR
    return np.sign(np.sin(2 * np.pi * f * t)) * 0.35 * np.minimum(1, (n - np.arange(n)) / 200)


def scream_sig(dur=1.7):
    n = int(SR * dur)
    t = np.arange(n) / SR
    f = 620 + 330 * np.minimum(t / 0.3, 1) + 45 * np.sin(2 * np.pi * 7 * t)
    ph = 2 * np.pi * np.cumsum(f) / SR
    x = 0.5 * np.sin(ph) + 0.35 * np.sign(np.sin(ph)) + 0.3 * noise_sig(n, 9)
    x = np.tanh(x * 2.4)
    env = np.minimum(t / 0.03, 1) * np.exp(-np.maximum(t - 1.0, 0) * 3.5)
    return x * env


def riser(dur, f0=60, f1=900, seed=4):
    n = int(SR * dur)
    t = np.arange(n) / SR
    k = (t / dur) ** 2
    f = f0 + (f1 - f0) * k
    x = np.sin(2 * np.pi * np.cumsum(f) / SR) * 0.6 + lowpass(noise_sig(n, seed), 4) * 0.5
    return x * k


def read_wav_mono(path):
    with wave.open(path, "rb") as w:
        n, ch, rate = w.getnframes(), w.getnchannels(), w.getframerate()
        raw = np.frombuffer(w.readframes(n), dtype=np.int16).astype(np.float32) / 32768.0
    if ch > 1:
        raw = raw.reshape(-1, ch).mean(axis=1)
    m = int(len(raw) * SR / rate)
    return np.interp(np.arange(m) * rate / SR, np.arange(len(raw)), raw)


def tts(text, voice="en-us+m3", speed=170, pitch=40, amp=170):
    exe = shutil.which("espeak-ng") or shutil.which("espeak")
    if not exe:
        return None
    path = tempfile.mktemp(suffix=".wav")
    try:
        subprocess.run([exe, "-v", voice, "-s", str(speed), "-p", str(pitch), "-a", str(amp), "-w", path, text],
                       check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        x = read_wav_mono(path)
    except Exception as exc:  # noqa: BLE001
        print("TTS failed:", exc)
        return None
    finally:
        if os.path.exists(path):
            os.remove(path)
    pk = np.max(np.abs(x)) or 1.0
    return x / pk * 0.85


def reverb(x):
    out = np.concatenate([x, np.zeros(int(SR * 0.8))])
    for dly, g in [(0.07, 0.5), (0.13, 0.38), (0.21, 0.28), (0.34, 0.18), (0.5, 0.1)]:
        k = int(dly * SR)
        out[k:k + len(x)] += x * g
    return out


def robot(x):
    t = np.arange(len(x)) / SR
    x = np.round(x * 7) / 7
    return x * (0.55 + 0.45 * np.sign(np.sin(2 * np.pi * 55 * t)))


def build_audio(path):
    total = int(SR * DURATION)
    mus = np.zeros(total)
    sfx = np.zeros(total)
    vo = np.zeros(total)
    tt = np.arange(total) / SR

    # --- suspense drone with automation (cuts, swells) ---
    drone = (np.sin(2 * np.pi * 55 * tt) * 0.5 + np.sin(2 * np.pi * 55.5 * tt) * 0.4
             + np.sin(2 * np.pi * 82.4 * tt + np.sin(2 * np.pi * 0.2 * tt) * 2) * 0.25
             + np.sin(2 * np.pi * 110.4 * tt) * 0.15 + np.sin(2 * np.pi * 164.8 * tt + 1.0) * 0.06)
    drone *= 0.75 + 0.25 * np.sin(2 * np.pi * 0.13 * tt)
    keys = [(0, 0), (1.5, 0.32), (5, 0.34), (9, 0.26), (21, 0.28), (23.8, 0.55), (23.95, 0.0),
            (T_HIT - 0.02, 0.0), (T_HIT + 0.6, 0.38), (28, 0.45), (33.8, 0.55), (33.95, 0.0),
            (36.6, 0.0), (38.5, 0.22), (43, 0.4), (50, 0.55), (56.85, 0.7), (56.95, 0.0), (60, 0.0)]
    env = np.interp(tt, [k[0] for k in keys], [k[1] for k in keys])
    mus += drone * env * 0.9
    # tension pads that rise in tense scenes
    pad = np.sin(2 * np.pi * 233 * tt) * 0.12 + np.sin(2 * np.pi * 246.9 * tt) * 0.12
    penv = np.interp(tt, [0, 21, 24, 24.1, 43, 50, 56.9, 57], [0, 0, 0.5, 0, 0.1, 0.5, 0.7, 0])
    mus += pad * penv * 0.25

    # --- sfx ---
    add(sfx, 4.55, heartbeat(), 0.9)  # single heartbeat in the hook
    for w in (9.0, 21.0, 43.0, 50.0):
        add(sfx, w - 0.25, whoosh(0.5), 0.25)
    # scene 2: ticking + footsteps
    k = 0
    while 5.0 + k * 0.5 < 9.0:
        add(sfx, 5.0 + k * 0.5, click(), 0.16)
        k += 1
    k = 0
    while 5.0 + k * 0.449 < 9.0:
        add(sfx, 5.0 + k * 0.449, footstep(k), 0.3)
        k += 1
    # scene 3: dings + giggle
    for tm in (9.8, 13.7, 17.6):
        add(sfx, tm, ding(), 0.5)
    for j, f in enumerate((900, 1150, 1400)):
        n = int(SR * 0.08)
        tg = np.arange(n) / SR
        add(sfx, 17.9 + j * 0.1, np.sin(2 * np.pi * f * tg) * np.exp(-tg * 25), 0.25)
    # scene 4: flickering lights, silence, bass hit
    for tm in (22.4, 22.9, 23.3, 23.6, 23.8):
        add(sfx, tm, glitch_burst(int(tm * 10), 0.09), 0.25)
    add(sfx, 21.8, riser(2.1, 70, 300), 0.2)
    add(sfx, T_HIT, thump(36, 90, 1.6, 2.6), 1.7)
    add(sfx, T_HIT, noise_sig(int(SR * 0.35), 12) * np.exp(-np.arange(int(SR * 0.35)) / SR * 14), 0.5)
    # scene 5: fast heartbeat, running footsteps, breathing
    k = 0
    while 28.0 + k * 0.46 < 33.8:
        add(sfx, 28.0 + k * 0.46, heartbeat(), 0.8)
        k += 1
    k = 0
    while 28.0 + k * 0.21 < 33.9:
        add(sfx, 28.0 + k * 0.21, footstep(100 + k), 0.38)
        k += 1
    k = 0
    while 28.4 + k * 0.85 < 33.5:
        add(sfx, 28.4 + k * 0.85, breath(300 + k), 0.2)
        k += 1
    # scene 6: near silence then a low sub-rumble under the whisper
    add(sfx, 36.0, riser(3.0, 40, 120), 0.12)
    # scene 7: glitch, alarm, rising bass
    k = 0
    while 43.0 + k * 0.33 < 49.9:
        add(sfx, 43.0 + k * 0.33, glitch_burst(700 + k, 0.1), 0.3 + 0.1 * (k % 3))
        k += 1
    for j in range(10):
        add(sfx, 43.7 + j * 0.55, beep(1800 if j % 2 == 0 else 1500), 0.16)
    add(sfx, 43.2, riser(6.7, 50, 600), 0.45)
    # scene 8: fast ticking, flips
    k = 0
    while 50.4 + k * 0.25 < 56.9:
        add(sfx, 50.4 + k * 0.25, click(), 0.22 + 0.06 * (k % 2))
        k += 1
    add(sfx, 50.2, riser(6.7, 60, 700, 8), 0.4)
    for j, tm in enumerate((53.0, 54.0, 55.0, 56.0)):
        add(sfx, tm, glitch_burst(900 + j, 0.2), 0.8 if j == 0 else 0.4)
    add(sfx, 53.0, thump(40, 100, 0.9, 4), 1.0)
    # scene 9: scream, then total silence
    add(sfx, 57.05, scream_sig(1.7), 0.8)
    add(sfx, 57.0, thump(40, 110, 0.6, 5), 1.0)

    # --- voiceover (espeak-ng) ---
    lines = [
        (0.2, "Imagine living in a world where everyone knows exactly when they're going to die.", dict(speed=185)),
        (5.2, "Everyone has a countdown above their head.", dict(speed=170)),
        (9.5, "Alex's best friend has 47 years remaining.", dict(speed=170)),
        (13.4, "His mother has 32 years.", dict(speed=170)),
        (17.3, "His little sister has 68 years.", dict(speed=170)),
        (21.4, "But when Alex checks his own countdown.", dict(speed=165)),
        (28.3, "He panics.", dict(speed=165)),
    ]
    got_tts = False
    for start, text, kw in lines:
        x = tts(text, **kw)
        if x is not None:
            add(vo, start, x, 0.9)
            got_tts = True
    x = tts("You're not supposed to be alive.", voice="en-us+whisper", speed=120, pitch=30, amp=200)
    if x is not None:
        add(vo, 36.5, reverb(x), 1.3)
    x = tts("Your death has been delayed.", voice="en-us+m1", speed=150, pitch=20)
    if x is not None:
        add(vo, 43.8, robot(x), 0.7)
    x = tts("Someone else will die in your place.", voice="en-us+m1", speed=150, pitch=20)
    if x is not None:
        add(vo, 47.0, robot(x), 0.7)
    x = tts("Nooooooo!", voice="en-us+m1", speed=95, pitch=80, amp=200)
    if x is not None:
        add(vo, 57.15, x, 0.9)
    if not got_tts:
        print("NOTE: espeak-ng not found - video will have music and SFX but no voiceover.")

    mix = mus + sfx + vo
    # real silence after the scream and the cut before the whisper
    mix[int(58.8 * SR):] = 0.0
    mix = np.tanh(mix * 1.1)
    pk = np.max(np.abs(mix)) or 1.0
    mix = mix / pk * 0.92
    pcm = (np.repeat(mix[:, None], 2, axis=1) * 32767).astype(np.int16)
    with wave.open(path, "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(pcm.tobytes())
    return path


