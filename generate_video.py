def box(d, x0, y0, x1, y1, col, depth=0.0):
    """Front face + lit top face + shaded side face = blocky 3D look."""
    if depth > 0:
        dx, dy = depth, depth * 0.75
        d.polygon([(x0, y0), (x1, y0), (x1 + dx, y0 - dy), (x0 + dx, y0 - dy)],
                  fill=shade(col, 1.3))
        d.polygon([(x1, y0), (x1 + dx, y0 - dy), (x1 + dx, y1 - dy), (x1, y1)],
                  fill=shade(col, 0.68))
    d.rectangle([x0, y0, x1, y1], fill=col)


