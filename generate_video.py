# main
# --------------------------------------------------------------------------
def main():
    if "--frames" in sys.argv:
        os.makedirs("preview", exist_ok=True)
        for tok in sys.argv[sys.argv.index("--frames") + 1].split(","):
            fr = int(float(tok) * FPS)
            data = render_frame(fr)
            Image.frombytes("RGB", (W, H), data).save(f"preview/frame_{tok}.png")
            print("saved preview/frame_%s.png" % tok)
        return

    if not shutil.which("ffmpeg"):
        sys.exit("ffmpeg not found. Install it (sudo apt-get install ffmpeg).")
    os.makedirs(os.path.dirname(OUT) or ".", exist_ok=True)
    wav = build_audio(os.path.join(tempfile.gettempdir(), "alex_audio.wav"))
    seconds = min(DURATION, float(os.environ.get("MAX_SECONDS", DURATION)))
    n = int(seconds * FPS)
    cmd = ["ffmpeg", "-y", "-loglevel", "error", "-f", "rawvideo", "-pix_fmt", "rgb24",
           "-s", f"{W}x{H}", "-r", str(FPS), "-i", "-", "-i", wav,
           "-map", "0:v", "-map", "1:a", "-c:v", "libx264", "-preset", "medium", "-crf", "24",
           "-pix_fmt", "yuv420p", "-profile:v", "high", "-r", str(FPS), "-g", "60",
           "-c:a", "aac", "-b:a", "192k", "-shortest", "-movflags", "+faststart", OUT]
    proc = subprocess.Popen(cmd, stdin=subprocess.PIPE)
    workers = max(1, os.cpu_count() or 1)
    print(f"Rendering {n} frames with {workers} worker(s)...", flush=True)
    try:
        with Pool(workers) as pool:
            for k, frame in enumerate(pool.imap(render_frame, range(n), chunksize=2)):
                proc.stdin.write(frame)
                if k % 90 == 0:
                    print(f"  frame {k}/{n}", flush=True)
    except BrokenPipeError:
        pass
    finally:
        try:
            proc.stdin.close()
        except Exception:  # noqa: BLE001
            pass
    code = proc.wait()
    if code != 0:
        sys.exit(f"ffmpeg failed with exit code {code}")
    print(f"Done: {OUT} ({os.path.getsize(OUT) / 1e6:.1f} MB)")


if __name__ == "__main__":
    main()
