_yy, _xx = np.mgrid[0:H, 0:W].astype(np.float32)
_r = np.sqrt(((_xx - W / 2) / (W / 2)) ** 2 + ((_yy - H / 2) / (H / 2)) ** 2)
VIGN = np.clip(1.15 - 0.42 * _r ** 2, 0.25, 1.0).astype(np.float32)[:, :, None]
del _yy, _xx, _r
_nrng = np.random.default_rng(5)
NOISE = [_nrng.integers(-3, 4, (H, W, 1), dtype=np.int8) for _ in range(3)]


def apply_camera(img, cam, t):
    zoom, cx, cy, shake = cam
    if zoom <= 1.0005 and shake <= 0:
        return img
    zoom = max(zoom, 1.0)
    zw, zh = W / zoom, H / zoom
    sx = shake * (math.sin(t * 61.0) + math.sin(t * 37.0 + 1.0)) * 0.5
    sy = shake * (math.sin(t * 53.0 + 2.0) + math.sin(t * 29.0)) * 0.5
    x0 = clamp(cx - zw / 2 + sx, 0, W - zw)
    y0 = clamp(cy - zh / 2 + sy, 0, H - zh)
    return img.resize((W, H), Image.BILINEAR, box=(x0, y0, x0 + zw, y0 + zh))


def glitch_fx(a, amt, rng):
    if amt <= 0.03:
        return a
    sh = int(amt * 30)
    out = a.copy()
    out[:, :, 0] = np.roll(a[:, :, 0], sh, axis=1)
    out[:, :, 2] = np.roll(a[:, :, 2], -sh, axis=1)
    for _ in range(int(2 + amt * 8)):
        y = int(rng.integers(0, H - 80))
        h = int(rng.integers(8, int(20 + amt * 150)))
        dx = int(rng.integers(-1, 2) * rng.integers(20, int(40 + amt * 240)))
        out[y:y + h] = np.roll(out[y:y + h], dx, axis=1)
    if amt > 0.5:
        y = int(rng.integers(0, H - 40))
        out[y:y + 6] = 255 - out[y:y + 6]
    return out


def post(img, fx, i, t):
    arr = np.asarray(img, dtype=np.float32)
    arr = arr * VIGN
    b = fx.get("bright", 1.0)
    if b != 1.0:
        arr = arr * b
    tint = fx.get("tint")
    if tint:
        a = tint[3]
        arr = arr * (1 - a) + np.array(tint[:3], np.float32) * a
    arr = arr + NOISE[i % 3]
    fl = fx.get("flash", 0.0)
    if fl > 0:
        col = np.array(fx.get("flash_col", (255, 255, 255)), np.float32)
        arr = arr * (1 - fl) + col * fl
    fade = fx.get("fade", 1.0)
    if fade < 1.0:
        arr = arr * fade
    out = np.clip(arr, 0, 255).astype(np.uint8)
    out = glitch_fx(out, fx.get("glitch", 0.0), np.random.default_rng(i + 7))
    return out


