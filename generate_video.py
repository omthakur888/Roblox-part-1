def clamp(x, a=0.0, b=1.0):
    return max(a, min(b, x))


def lerp(a, b, t):
    return a + (b - a) * t


def ease(t):
    t = clamp(t)
    return t * t * (3 - 2 * t)


def shade(c, f):
    return tuple(int(clamp(v * f, 0, 255)) for v in c)


def mixc(c1, c2, t):
    return tuple(int(lerp(a, b, t)) for a, b in zip(c1, c2))


def burst(t, rate):
    """Irregular 0/1 pulses used for flicker and glitch timing."""
    return 1.0 if math.sin(t * rate) * math.sin(t * rate * 1.73 + 1.1) > 0.55 else 0.0


